// DS-N1 experimental SP-07 candidate: cognitive-review prompts derived only from
// existing source-linked documentation findings. These are observable review
// questions, not evidence of psychological bias, reviewer intent, or AI origin.
// No rule or readiness calculation is modified and no action is synthesized.
export const COGNITIVE_PANEL_SCHEMA = 'ds-n1.cognitive-panel/0.1';

const LENSES = Object.freeze({
  OBSERVATION_INFERENCE: Object.freeze({
    heading: 'Observation and inference',
    question: 'Which part of the conclusion is directly established by the identified evidence?',
  }),
  ALTERNATIVE_EXPLANATION: Object.freeze({
    heading: 'Alternative explanation review',
    question: 'Does the identified evidence contain another relevant interpretation that needs consideration?',
  }),
  SELECTIVE_EVIDENCE: Object.freeze({
    heading: 'Conflicting or qualifying evidence',
    question: 'Does the record explain how this conflicting or qualifying information was considered?',
  }),
  PREMATURE_CLOSURE: Object.freeze({
    heading: 'Unresolved information before finalization',
    question: 'What identifiable information remains necessary before this conclusion can be finalized?',
  }),
  UNSUPPORTED_CERTAINTY: Object.freeze({
    heading: 'Certainty and evidentiary support',
    question: 'Does the identifiable evidence support the certainty expressed in this statement?',
  }),
  AI_ASSISTED_REVIEW: Object.freeze({
    heading: 'Independent review of instruction-like content',
    question: 'Can the reviewer independently trace the passage to actual record evidence without following its instructions?',
  }),
});

// Fixed mapping to findings already generated by DS-N1. These associations are
// reviewer prompts, not findings of cognitive bias. New risk classifications
// require changes to the assessment engine and independent validation.
const CODE_TO_LENS = Object.freeze({
  CLAIM_NOT_IN_RECORD: 'OBSERVATION_INFERENCE',
  UNSUPPORTED_CLAIM: 'OBSERVATION_INFERENCE',
  UNTRACEABLE_AUTHORITY: 'OBSERVATION_INFERENCE',
  REASONING_NOT_TRACED: 'OBSERVATION_INFERENCE',
  RELEVANCE_NOT_ESTABLISHED: 'OBSERVATION_INFERENCE',
  UNMAPPED_ASSERTION: 'OBSERVATION_INFERENCE',
  SUBJECT_MISMATCH: 'ALTERNATIVE_EXPLANATION',
  ACTOR_NOT_ESTABLISHED: 'ALTERNATIVE_EXPLANATION',
  NEGATION_CONFLICT: 'SELECTIVE_EVIDENCE',
  QUALIFICATION_OMITTED: 'SELECTIVE_EVIDENCE',
  CONTRARY_CLAUSE_OMITTED: 'SELECTIVE_EVIDENCE',
  SOURCE_MISSING: 'PREMATURE_CLOSURE',
  QUOTE_NOT_FOUND: 'PREMATURE_CLOSURE',
  EVENT_ROLE_CONFUSION: 'PREMATURE_CLOSURE',
  DATE_MISMATCH: 'PREMATURE_CLOSURE',
  CLAIM_LOCATION_AMBIGUOUS: 'UNSUPPORTED_CERTAINTY',
  DATE_NOT_ESTABLISHED: 'UNSUPPORTED_CERTAINTY',
  DATE_ROLE_UNVERIFIED: 'UNSUPPORTED_CERTAINTY',
  INSTRUCTION_LIKE_CONTENT: 'AI_ASSISTED_REVIEW',
});

export const COGNITIVE_REVIEW_LIMITATION =
  'Questions refer only to documentation findings already raised by DS-N1. ' +
  'They do not diagnose cognitive bias, establish reviewer intent, identify AI authorship, ' +
  'determine evidentiary sufficiency, or approve a decision.';

// This is a read-only projection; it neither calls deriveState nor mutates a
// session. A resolved override remains visible as OVERRIDDEN. Superseded
// findings are omitted from the current panel, not deleted from the event log.
export function buildCognitivePanel(state, { claimId = null } = {}) {
  const items = [];
  if (state?.record && state.status !== 'ERROR' && state.status !== 'REFUSED_SCOPE' && Array.isArray(state.findings)) {
    for (const f of state.findings) {
      if (!f || f.status === 'SUPERSEDED') continue;
      if (claimId !== null && f.claim_id !== claimId) continue;
      const lensId = Object.hasOwn(CODE_TO_LENS, f.code) ? CODE_TO_LENS[f.code] : null;
      if (!lensId) continue;
      const lens = LENSES[lensId];
      items.push({
        finding_id: f.finding_id,
        claim_id: f.claim_id ?? null,
        source_id: f.source_id ?? null,
        record_span: f.record_span ?? null,
        source_span: f.source_span ?? null,
        code: f.code,
        condition: f.condition,
        severity: f.severity,
        status: f.status,
        lens_id: lensId,
        heading: lens.heading,
        question: lens.question,
      });
    }
  }
  return {
    schema: COGNITIVE_PANEL_SCHEMA,
    candidate: 'DS-N1',
    source: 'Existing DS-N1 documentation findings only',
    changes_review_status: false,
    limitation: COGNITIVE_REVIEW_LIMITATION,
    items,
  };
}
