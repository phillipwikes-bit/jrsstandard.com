#!/usr/bin/env node
// Builds the SYNTHETIC demonstration packet the workspace can open and download.
//   node tools/local-reviewer-workspace/make-demo-packet.mjs           write app/demo-packet.js
//   node tools/local-reviewer-workspace/make-demo-packet.mjs --check   fail if the committed file is stale
//
// Synthetic only: the source is tests/engine-candidate/fixtures/SYNTHETIC-SAE-03-GAPS.txt, a
// constructed record of fictional people already registered as development material, and the
// model is the candidate's deterministic mock adapter. No provider, no real record, no network.
import { readFileSync, writeFileSync } from 'node:fs';
import { runCandidate, CONDITION_KEYS, PROMPT_VERSION } from '../../lib/engine-candidate/review-candidate.js';
import { buildReviewerPacket } from '../../lib/engine-candidate/reviewer-packet.js';
import { createMockAdapter } from '../../lib/engine-candidate/mock-adapter.js';
import { explanationIdFor, ADAPTER_CONTRACT } from '../../lib/engine-candidate/adapter.js';

const ROOT = new URL('../../', import.meta.url).pathname;
const SOURCE = 'tests/engine-candidate/fixtures/SYNTHETIC-SAE-03-GAPS.txt';
const OUT = new URL('./app/demo-packet.js', import.meta.url).pathname;
const IDS = { model_id: 'mock-demo', model_version: 'synthetic', prompt_version: PROMPT_VERSION };

export async function buildDemoPacket() {
  const text = readFileSync(ROOT + SOURCE, 'utf8');
  const note = 'The record states this only in part.';
  const conditions = Object.fromEntries(CONDITION_KEYS.map((k) => [k, { status: 'review', explanation_id: explanationIdFor('condition', k), note, uncertain: false }]));
  conditions.cold_reviewer_clarity.note = 'The approver was clearly frustrated with the delay.';   // withheld by the person-inference screen, so the demo shows a model-output check
  const response = {
    adapter_contract: ADAPTER_CONTRACT, ...IDS, completion: 'complete', conditions,
    findings: [
      { type: 'evidentiary_overreach', quotation: 'clearly a trusted partner', explanation_id: explanationIdFor('flaw', 'evidentiary_overreach'), note: 'Trust is asserted, and no basis for it is recorded.', uncertain: false },
      { type: 'reasoning_elision', quotation: 'As discussed on the call, the agreement will follow.', explanation_id: explanationIdFor('flaw', 'reasoning_elision'), note: 'The required agreement is deferred without saying why access proceeded first.', uncertain: true },
    ],
    revision_needed: null,
  };
  const adapter = createMockAdapter({ ...IDS, respond: () => response });
  const profile = { record_type: 'supplier_access_exception', completion_status: 'completed', hr_related: false };
  const result = await runCandidate({ text, profile, record_ref: 'SYNTHETIC-DEMO-SAE-03' }, { adapter, now: () => '2026-10-06T00:00:00Z' });
  return buildReviewerPacket(result, text);
}

export function demoModuleText(packet) {
  return '// GENERATED by tools/local-reviewer-workspace/make-demo-packet.mjs. Do not edit by hand.\n'
    + '// SYNTHETIC DEMONSTRATION PACKET: a constructed record of fictional people (' + SOURCE + ')\n'
    + '// reviewed by the candidate\'s mock adapter. Not a real record and not a real model output.\n'
    + 'export const SYNTHETIC_DEMO_NOTICE = \'SYNTHETIC DEMONSTRATION PACKET. Constructed record, fictional people, mocked model output. Not a real record.\';\n'
    + 'export const SYNTHETIC_DEMO_PACKET = ' + JSON.stringify(packet, null, 1) + ';\n';
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = demoModuleText(await buildDemoPacket());
  if (process.argv.includes('--check')) {
    const same = readFileSync(OUT, 'utf8') === text;
    console.log(same ? 'PASS  app/demo-packet.js is current' : 'FAIL  app/demo-packet.js is stale; regenerate it');
    process.exit(same ? 0 : 1);
  }
  writeFileSync(OUT, text);
  console.log('wrote ' + OUT);
}
