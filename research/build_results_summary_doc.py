#!/usr/bin/env python3
"""Render the completer results summary to a document, from the live endpoint.

WHY IT PULLS RATHER THAN RETYPES. The summary text lives in api/contributor.js
and is the thing 36 people will actually be shown. A second copy typed into a
markdown file is a second copy of a fact with nothing forcing it to agree with
the first, which is the defect class this repository keeps hitting. This posts
the same submission a contributor's browser posts, using the endpoint's built-in
self-test key so no row is written and no counter moves, and renders whatever
comes back.

If the endpoint text changes, re-run this and the document changes with it. If
the endpoint is unreachable or the summary is not released, it says so and
writes nothing rather than emitting a stale copy.

Run:
    python3 research/build_results_summary_doc.py

Exit code: 0 on success, 1 if the endpoint could not be read or the results are
not released.
"""
import io
import json
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ENDPOINT = "https://www.jrsstandard.com/api/contributor"
TEST_KEY = "selftest00"          # api/contributor.js TEST_KEY: resolves, writes nothing
OUT = os.path.join(HERE, "Completer_Results_Summary_2026-08-15.md")


def fetch():
    body = json.dumps({
        "k": TEST_KEY,
        "consent_named": "no",
        "consent_use": "yes",
        "consent_transfer": "yes"
    }).encode("utf-8")
    req = urllib.request.Request(
        ENDPOINT, data=body,
        headers={"Content-Type": "application/json"},
        method="POST")
    with urllib.request.urlopen(req, timeout=45) as r:
        return json.loads(r.read().decode())


def main():
    try:
        d = fetch()
    except Exception as e:
        sys.stderr.write("Could not reach %s: %s\nNothing written.\n" % (ENDPOINT, e))
        return 1

    if not d.get("test"):
        sys.stderr.write("The endpoint did not flag this as a test submission. "
                         "Refusing to continue: a real row may have been written.\n")
        return 1

    r = d.get("results") or {}
    if r.get("status") != "released":
        sys.stderr.write("Results are not released (status=%r). Nothing written.\n"
                         % r.get("status"))
        return 1

    L = []
    A = L.append
    A("# What the study found")
    A("")
    A("**The results summary sent to every completer.** Locked %s."
      % r.get("locked_on", "(no lock date returned)"))
    A("")
    A("**Generated by `research/build_results_summary_doc.py` from the live "
      "`/api/contributor` response.** Not retyped. This is the exact text a "
      "contributor sees after submitting their confirmation, pulled by posting the "
      "same submission their browser posts, using the endpoint's self-test key so "
      "no row is written and no counter moves.")
    A("")
    A("**How a contributor reaches it.** One unguessable link each. Opening the link "
      "shows their name and title on file and nothing else: the summary is returned "
      "only after they submit the three forced-choice permissions. A GET on the link "
      "carries no results field at all, so forwarding or fetching a link discloses "
      "nothing.")
    A("")
    A("---")
    A("")

    if r.get("opening"):
        A(r["opening"])
        A("")

    if r.get("scale"):
        A("## Scale")
        A("")
        for x in r["scale"]:
            A("- %s" % x)
        A("")

    if r.get("published"):
        A("## Findings")
        A("")
        for x in r["published"]:
            if ". " in x[:70] and x.split(". ")[0].isupper():
                head, rest = x.split(". ", 1)
                A("### %s" % head.title())
                A("")
                A(rest)
            elif x[:40].isupper() or x.split(",")[0].isupper():
                A("**%s**" % x)
            else:
                A(x)
            A("")

    if r.get("what_your_work_supports"):
        A("## What your work supports")
        A("")
        for x in r["what_your_work_supports"]:
            A("- %s" % x)
        A("")

    if r.get("closing"):
        A("---")
        A("")
        A(r["closing"])
        A("")

    A("---")
    A("")
    A("## Also released on submission")
    A("")
    g = d.get("guides") or {}
    for k in sorted(g):
        A("- Investigator Field Guide, %s: `%s`" % (k, g[k]))
    if d.get("training"):
        A("- Training: `%s`" % d["training"])
    A("")

    io.open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote %s" % OUT)
    print("  status: %s | locked_on: %s" % (r.get("status"), r.get("locked_on")))
    print("  sections: scale %d | findings %d | supports %d"
          % (len(r.get("scale") or []), len(r.get("published") or []),
             len(r.get("what_your_work_supports") or [])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
