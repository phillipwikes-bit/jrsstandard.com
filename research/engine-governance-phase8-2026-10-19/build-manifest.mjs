#!/usr/bin/env node
// JRS PHASE 8: writes PHASE8_FILE_MANIFEST_SHA256.txt over every Phase 8 file except the declared exclusions.
//   node research/engine-governance-phase8-2026-10-19/build-manifest.mjs

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CURRENT_PACKAGE, listFiles, buildManifest, STATUS_LINES } from '../../lib/engine-governance-phase8/registry.mjs';

const REPO = fileURLToPath(new URL('../../', import.meta.url));
export const EXCLUDED = ['research/engine-governance-phase8-2026-10-19/PHASE8_FILE_MANIFEST_SHA256.txt', 'research/engine-governance-phase8-2026-10-19/execution-record/PHASE8_TEST_RESULTS.json', 'research/engine-governance-phase8-2026-10-19/execution-record/MUTATION_EVIDENCE.json', 'research/engine-governance-phase8-2026-10-19/governance/LATER_PACKAGE_REGISTRY.json', 'research/engine-governance-phase8-2026-10-19/execution-record/WORKTREE_RUN_RECORD.json'];
export const EXCLUDED_PREFIX = 'research/engine-governance-phase8-2026-10-19/execution-record/worktree-output/';

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const pkg = Object.assign({}, CURRENT_PACKAGE);
  const m = buildManifest(REPO, pkg);
  const rows = m.files.filter((f) => !EXCLUDED.includes(f.path) && !f.path.startsWith(EXCLUDED_PREFIX));
  const head = STATUS_LINES.map((s) => '# ' + s).concat(['# SHA-256 of every Phase 8 file, sorted by path. Excluded: this file, the two files the suite writes with --record, the later-package registry, which binds this manifest by hash, and the whole-worktree run record with its suite outputs, which are regenerated by every run and recomputed by the suite (' + EXCLUDED.slice(1).join(', ') + ').',
    '# Verify: grep -v "^#" PHASE8_FILE_MANIFEST_SHA256.txt | sha256sum -c   (from the repository root)']);
  writeFileSync(join(REPO, EXCLUDED[0]), head.join('\n') + '\n' + rows.map((f) => f.sha256 + '  ' + f.path).join('\n') + '\n');
  console.log('manifest: ' + rows.length + ' files');
}
