// Synthetic-only IncomeOS recovery and savings controls.
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {resolve} from "node:path";
import {Script,runInNewContext} from "node:vm";
const dir=resolve("owner/incomeos"),read=p=>readFileSync(resolve(dir,p),"utf8");
const engine=read("recovery-engine.js"),ui=read("recovery-ui.js"),page=read("index.html");
new Script(engine);new Script(ui);
const ctx={window:{},Date,Math,Array,Object,Map,Set,Number,String,JSON,Error};
runInNewContext(engine,ctx);
const rec=ctx.window.IncomeOSRecovery;
const expense=(id,date,amountUsd,ref)=>({id,kind:"outflow",type:"expense",date,amountUsd,label:"Vendor charged",payer:"Test Vendor",bankSource:ref?{institution:"Synthetic Bank",accountToken:"masked-1234",transactionId:ref}:null});
let rows=[expense("one","2026-10-01",25,"posting-a"),expense("two","2026-10-01",25,"posting-b")];
let result=rec.analyze(rows,null,[]);
assert.equal(result.duplicateChargeCandidates.length,1);
assert.equal(result.duplicateChargeCandidates[0].sourceDistinct,true);
assert.equal(result.confirmedNewIncomeUsd,0);
assert.equal(result.claimActionsTaken,0);
assert.equal(rec.duplicateCandidates([expense("one","2026-10-01",25,"same"),expense("two","2026-10-01",25,"same")]).length,0,"Same posting imported twice is not a second merchant charge");
assert.equal(rec.duplicateCandidates([expense("one","2026-10-01",25,"a"),expense("two","2026-10-20",25,"b")]).length,0);
assert.equal(rec.duplicateCandidates([expense("one","2026-10-01",25,"a"),expense("two","2026-10-01",26,"b")]).length,0);
assert.equal(rec.duplicateCandidates([expense("one","2026-10-01",25,"a"),expense("two","2026-10-02",25,"b")]).length,1);
const refund={id:"refund1",kind:"income",scope:"nonincome",status:"paid",date:"2026-10-05",grossUsd:10,refundOf:"one"};
const report={matches:[{entryId:"one",state:"OWNER_REVIEWED_BANK_MATCH"},{entryId:"refund1",state:"OWNER_REVIEWED_BANK_MATCH"}]};
result=rec.analyze([rows[0],refund],report,[]);
assert.equal(result.refundReviews[0].state,"OWNER_REVIEWED_BANK_CREDIT");
assert.equal(result.refundReviews[0].countsAsNewEarnings,false);
assert.equal(result.refundReviews[0].confirmedRecoveredUsd,10);
result=rec.analyze([rows[0],refund],{matches:[]},[]);
assert.equal(result.refundReviews[0].state,"OWNER_REFUND_ENTRY_UNCONFIRMED");
assert.equal(result.refundReviews[0].confirmedRecoveredUsd,0);
result=rec.analyze([rows[0],{...refund,grossUsd:30}],report,[]);
assert.equal(result.refundReviews[0].state,"AMOUNT_OR_DATE_CONFLICT");
assert.equal(result.refundReviews[0].confirmedRecoveredUsd,0);
result=rec.analyze([rows[0],{...refund,refundOf:"not-found"}],report,[]);
assert.equal(result.refundReviews[0].state,"UNLINKED_NONINCOME_RECEIPT");
assert.equal(result.refundReviews[0].confirmedRecoveredUsd,0);
function bill(month,amountUsd,verified=true){return {provider:"Example ISP",service:"Home internet same plan",month,amountUsd,confirmedEquivalentService:verified,sourceStatus:"owner-reviewed-bill-and-bank"};}
const billRows=[bill("2026-07",100),bill("2026-08",80),bill("2026-09",80)];
const savings=rec.savingReview(billRows);
assert.equal(savings.length,1);
assert.equal(savings[0].observedTwoCycleSavingsUsd,40);
assert.equal(savings[0].monthlyRunRateNotGuaranteedUsd,20);
assert.equal(savings[0].earnings,false);
assert.equal(rec.savingReview([bill("2026-07",100),bill("2026-08",80)]).length,0,"One lower bill is insufficient");
assert.equal(rec.savingReview([bill("2026-07",100),bill("2026-08",80),bill("2026-10",80)]).length,0,"Non-consecutive post-change bills are insufficient");
assert.equal(rec.savingReview([bill("2026-07",100),bill("2026-08",80),bill("2026-09",80,false)]).length,0,"Unknown service equivalence blocks savings claim");
assert.equal(rec.savingReview([bill("2026-07",100),bill("2026-08",80),bill("2026-09",80),bill("2026-09",80)]).length,0,"Conflicting same-month source rows require review");
assert.match(page,/recovery-review-panel/);
assert.match(page,/recovery-engine\.js/);
assert.match(page,/recovery-ui\.js/);
assert.doesNotMatch(engine+ui,/XMLHttpRequest|WebSocket|sendBeacon|fetch\s*\(/);
console.log("IncomeOS recovery QA passed: possible duplicates, refund linkage, principal exclusion, verified-bill baseline and savings guardrails.");
