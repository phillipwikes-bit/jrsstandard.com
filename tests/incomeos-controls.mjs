const fake={window:{},crypto:webcrypto,TextEncoder,TextDecoder,btoa,atob,Uint8Array,Date,JSON,Object,Array,String,Error};
runInNewContext(vault,fake);
const safe=fake.window.IncomeOSVault;
const map=new Map([["incomeos.accountant.v1",JSON.stringify({version:2,entries:[{description:"SYNTHETIC_PRIVATE_MARKER"}]})],["incomeos.owner.prototype.v1",JSON.stringify({saved:["test"]})]]);
const storage={getItem:(k)=>map.get(k)??null,setItem:(k,v)=>map.set(k,v),removeItem:(k)=>map.delete(k)};
const backup=safe.capture(storage);
const pass="correct horse battery staple for test only";
const encrypted=await safe.encrypt(pass,backup);
assert.doesNotMatch(encrypted,/SYNTHETIC_PRIVATE_MARKER/);
const decoded=await safe.decrypt(pass,encrypted);
assert.equal(decoded.values["incomeos.accountant.v1"],map.get("incomeos.accountant.v1"));
await assert.rejects(()=>safe.decrypt("wrong password padded 16",encrypted));
let tampered=JSON.parse(encrypted),data=tampered.data;
tampered.data=(data[0]==="A"?"B":"A")+data.slice(1);
await assert.rejects(()=>safe.decrypt(pass,JSON.stringify(tampered)));
const newMap=new Map();
safe.restore({setItem:(k,v)=>newMap.set(k,v),removeItem:(k)=>newMap.delete(k)},decoded);
assert.equal(newMap.get("incomeos.owner.prototype.v1"),map.get("incomeos.owner.prototype.v1"));
assert.throws(()=>safe.verify({version:1,values:{"localStorage.any":JSON.stringify({})}}));
