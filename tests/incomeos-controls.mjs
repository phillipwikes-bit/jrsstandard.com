runInNewContext(decision,obj);
const engine=obj.window.IncomeOSDecisionEngine;
assert.equal(engine.VERSION,"1.0.0");
assert.equal(engine.scenario({initial:0,monthly:100,years:1,annualReturnPct:0,annualFeePct:0,taxDragPct:0,inflationPct:0}).nominal,1200);
assert.equal(engine.scenario({initial:1000,monthly:0,years:1,annualReturnPct:10,annualFeePct:0,taxDragPct:0,inflationPct:0}).nominal,1100);
assert.equal(engine.scenario({initial:1000,monthly:0,years:1,annualReturnPct:0,annualFeePct:2,taxDragPct:0,inflationPct:0}).nominal,980);
assert.equal(engine.scenario({initial:1000,monthly:0,years:1,annualReturnPct:-20,annualFeePct:0,taxDragPct:0,inflationPct:0}).nominal,800);
assert.ok(engine.scenario({initial:1000,monthly:0,years:1,annualReturnPct:10,annualFeePct:0,taxDragPct:20,inflationPct:3}).realTodayDollars<1100);
assert.throws(()=>engine.scenario({initial:0,monthly:1,years:10,annualReturnPct:-100,annualFeePct:0,taxDragPct:0,inflationPct:0}),RangeError);
assert.throws(()=>engine.scenario({initial:0,monthly:1,years:1.5,annualReturnPct:0,annualFeePct:0,taxDragPct:0,inflationPct:0}),RangeError);
const candidate={id:"synthetic-asset-1",sourceUrl:"https://example.org/offer/1",reviewed:"2026-11-01",capitalUsd:100};
