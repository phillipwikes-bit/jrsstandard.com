// Synthetic-only accounting controls. No real statements, owner records or credentials.
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {resolve} from "node:path";
import {Script,runInNewContext} from "node:vm";
const root=resolve("owner/incomeos"),read=p=>readFileSync(resolve(root,p),"utf8");
const source=read("accounting-controls.js"),ui=read("accounting-controls-ui.js"),html=read("index.html"),security=read("SECURITY-AND-RELEASE.md");
new Script(source);new Script(ui);
const ctx={window:{},Date,Number,Map,Set,Array,Math,String,Object,JSON,Error};
runInNewContext(source,ctx);
const engine=ctx.window.IncomeOSAccountingControls;
assert.equal(engine.validDate("2026-11-01"),true);
assert.equal(engine.validDate("2026-02-29"),false);
assert.equal(engine.cents("12.30"),1230);
assert.equal(engine.cents(0.25),25);
assert.equal(engine.cents("-1.05"),-105);
for(const v of ["",null,"2.345","1e3","NaN",1.005])assert.throws(()=>engine.cents(v));
const ref=(id,accountToken="card-last4-3321")=>({institution:"Demo Bank",accountToken,transactionId:id});
const bank=(id,date,amountUsd,direction="debit")=>({...ref(id),date,amountUsd,direction,posted:true,currency:"USD",description:"Synthetic matching source"});
const income=(id,date,grossUsd,feesUsd,kind="research",status="paid")=>({id,kind:"income",scope:"income",category:kind,
  date,grossUsd,feesUsd,status,payer:"Synthetic Study",reconciled:true,bankSource:ref("source-"+id),reference:"doc-"+id});
const cost=(id,date,amountUsd,sourceId="source-"+id)=>({id,kind:"outflow",type:"expense",category:"software",
  date,amountUsd,businessUse:null,payer:"Synthetic Software",evidenceStatus:"both",reconciled:true,
  bankSource:ref(sourceId),reference:"inv-"+id});
const coverage=[{institution:"Demo Bank",accountToken:"card-last4-3321",from:"2026-01-01",through:"2026-11-30",complete:true,sourceVerified:true}];
const ledger=[income("paid1","2026-10-05",120,5),cost("cost1","2026-10-06",20),income("pending1","2026-10-06",300,0,"research","pending")];
const banks=[bank("source-paid1","2026-10-06",115,"credit"),bank("source-cost1","2026-10-06",20)];
let r=engine.analyze(ledger,banks,coverage);
assert.equal(r.ledger.submitted,3);
assert.equal(r.ledger.ownerReviewedBankMatches,2);
assert.equal(r.ledger.pending,1);
assert.equal(r.receivedByClassSelfReported["earned-or-other-income"],120);
assert.equal(r.reviewedBankLinkedByClass["earned-or-other-income"],120);
assert.equal(r.receivedByClassSelfReported.pending,undefined);
assert.equal(r.closeGate.status,"READY_FOR_ADDITIONAL_ACCOUNTANT_REVIEW");
assert.equal(r.closeGate.readyForTaxFiling,false);
assert.equal(r.closeGate.independentlyAudited,false);
assert.equal(r.closeGate.executable,false);
assert.ok(r.issues.some(x=>x.code==="UNKNOWN_ALLOCATION"),"Blank business allocation remains unresolved");
r=engine.analyze(ledger,banks,[]);
assert.equal(r.closeGate.status,"HOLD");
assert.ok(r.closeGate.blockers.some(x=>x.code==="SOURCE_COVERAGE"));
r=engine.analyze(ledger,banks.slice(0,1),coverage);
assert.equal(r.closeGate.status,"HOLD");
assert.ok(r.issues.some(x=>x.code==="MISSING_BANK_SOURCE"));
r=engine.analyze(ledger,[bank("source-paid1","2026-10-06",114,"credit"),banks[1]],coverage);
assert.equal(r.closeGate.status,"HOLD");
assert.ok(r.issues.some(x=>x.code==="BANK_LINK_MISMATCH"));
r=engine.analyze(ledger,[...banks,bank("source-paid1","2026-10-07",999,"credit")],coverage);
assert.ok(r.issues.some(x=>x.code==="CONFLICTING_SOURCE_ID"));
assert.equal(r.closeGate.status,"HOLD");
r=engine.analyze([...ledger,cost("cost2","2026-10-06",20,"source-cost1")],banks,coverage);
assert.ok(r.issues.some(x=>x.code==="BANK_LINK_COLLISION"));
assert.equal(r.closeGate.status,"HOLD");
r=engine.analyze([...ledger,cost("cost1","2026-10-07",20)],banks,coverage);
assert.ok(r.issues.some(x=>x.code==="DUPLICATE_LEDGER_ID"));
assert.equal(r.closeGate.status,"HOLD");
r=engine.analyze(ledger,[...banks,bank("unknown-credit","2026-10-08",500,"credit")],coverage);
assert.ok(r.issues.some(x=>x.code==="UNASSIGNED_BANK_POSTING"));
assert.equal(r.reviewedBankLinkedByClass["earned-or-other-income"],120,"Unclassified bank credit is not earned income");
assert.equal(r.closeGate.status,"HOLD");
r=engine.analyze([cost("costUnlinked","2026-10-06",20,"missing-bank-id")],banks,coverage);
assert.equal(r.ledger.ownerReviewedBankMatches,0);
assert.ok(r.suggestions[0].candidateCount>=1);
assert.equal(r.suggestions[0].state,"UNVERIFIED_DATE_AMOUNT_CANDIDATES");
assert.equal(r.closeGate.status,"HOLD");
r=engine.analyze([{...income("recovery1","2026-10-05",90,0),scope:"nonincome"}],[bank("source-recovery1","2026-10-05",90,"credit")],coverage);
assert.equal(r.receivedByClassSelfReported["recovery-or-return-of-principal"],90);
assert.equal(r.receivedByClassSelfReported["earned-or-other-income"],undefined);
assert.ok(r.issues.some(x=>x.code==="NONINCOME_RECEIPT"));
r=engine.analyze([cost("x1","2026-10-05",20),cost("x2","2026-10-05",20)],[
  bank("source-x1","2026-10-05",20),bank("source-x2","2026-10-05",20)],coverage);
assert.equal(r.ledger.ownerReviewedBankMatches,2,"Distinct transaction references survive same-day equal-amount imports");
assert.equal(r.bank.distinct,2);
assert.equal(engine.analyze([], [bank("source-x1","2026-10-05",20),bank("source-x1","2026-10-05",20)],coverage).bank.duplicateCount,1);
assert.throws(()=>engine.normalizedBank(bank("raw-account","2026-10-05",20,"debit").constructor===Object?{...bank("raw-account","2026-10-05",20),accountToken:"1234567890123456"}:{}));
assert.throws(()=>engine.normalizedBank({...bank("pending-posting","2026-10-05",20),posted:false}));
assert.throws(()=>engine.normalizedBank({...bank("foreign","2026-10-05",20),currency:"EUR"}));
assert.match(html,/id="accounting-control-panel"/);
assert.match(html,/accounting-controls\.js/);
assert.match(html,/accounting-controls-ui\.js/);
assert.match(ui,/analyze\(entries,\[\],\[\]\)/,"Browser must not pretend to receive bank transactions");
assert.doesNotMatch(source+ui,/XMLHttpRequest|WebSocket|sendBeacon|fetch\s*\(/);
assert.match(security,/P0, blocking/);
console.log("IncomeOS accounting controls QA passed: cents, source identity, reconciliation, duplicate references, refund classification, fail-closed close gate and privacy.");
