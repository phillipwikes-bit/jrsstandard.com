// IncomeOS event-journal acceptance checks. Synthetic-only, zero owner data.
import assert from "node:assert/strict";
import {webcrypto} from "node:crypto";
import {readFileSync} from "node:fs";
import {resolve} from "node:path";
import {Script,runInNewContext} from "node:vm";
const source=readFileSync(resolve("owner/incomeos/financial-event-journal.js"),"utf8");
new Script(source);
const context={window:{},Date,JSON,Array,Number,String,Object,Map,Set,Math,Error,TextEncoder,Uint8Array,crypto:webcrypto};
runInNewContext(source,context);
const J=context.window.IncomeOSEventJournal;
let history=[];
const e=(id,type,data)=>({id,type,timestamp:"2026-11-01T20:30:00.000Z",data});
const posted=(id,sourceId,amountCents,direction="credit")=>e(id,"POSTED",{sourceId,postedDate:"2026-11-01",direction,amountCents,currency:"USD",evidenceId:"provider.bank.2026"});
const classify=(id,post,label)=>e(id,"CLASSIFIED",{postedEventId:post,classification:label,evidenceId:"owner.classification.2026"});
const review=(id,post,cl)=>e(id,"OWNER_RECONCILED",{postedEventId:post,classificationEventId:cl,reviewEvidenceId:"owner.review.2026"});
const undo=(id,target)=>e(id,"REVERSED",{targetEventId:target,reasonEvidenceId:"owner.amendment.2026"});
history=await J.append(history,posted("posted.001","bank.posting.a",12500));
const original=JSON.stringify(history);
assert.equal((await J.verify(history)).count,1);
assert.equal((await J.verify(history)).headHash.length,64);
assert.notEqual((await J.verify(history)).headHash,J.genesisHash);
assert.deepEqual(JSON.parse(original),JSON.parse(JSON.stringify(history)),"Append must not mutate prior history");
await assert.rejects(J.append(history,posted("posted.002","bank.posting.a",12500)),/Source ID already recorded/);
await assert.rejects(J.append(history,classify("class.001","missing.posted","earned_income")),/requires an active posted/);
await assert.rejects(J.append(history,classify("class.001","posted.001","business_expense")),/direction/);
history=await J.append(history,classify("class.001","posted.001","earned_income"));
await assert.rejects(J.append(history,classify("class.002","posted.001","refund")),/Reverse previous classification/);
await assert.rejects(J.append(history,e("doc.001","DOCUMENT_MATCHED",{postedEventId:"posted.001",documentId:"receipt.001",amountCents:12400})),/amount/);
history=await J.append(history,e("doc.001","DOCUMENT_MATCHED",{postedEventId:"posted.001",documentId:"receipt.001",amountCents:12500}));
history=await J.append(history,review("review.001","posted.001","class.001"));
let report=await J.report(history);
assert.equal(report.earnedIncomeUsd,125);
assert.equal(report.returnedCapitalUsd,0);
assert.equal(report.ownerReviewedPostings,1);
assert.equal(report.closeGate.status,"JOURNAL_REVIEW_COMPLETE_ONLY");
assert.equal(report.closeGate.readyForTaxFiling,false);
assert.equal(report.closeGate.allAccountsCovered,false);
assert.equal(report.closeGate.canTransferFunds,false);
await assert.rejects(J.append(history,review("review.dup","posted.001","class.001")),/active reconciliation/);
await assert.rejects(J.append(history,undo("reversal.bad","class.001")),/Reverse reconciliation before/);
await assert.rejects(J.append(history,undo("reversal.bad","posted.001")),/Reverse dependent records before/);
history=await J.append(history,undo("reversal.review","review.001"));
report=await J.report(history);
assert.equal(report.earnedIncomeUsd,0);
assert.equal(report.closeGate.status,"HOLD");
history=await J.append(history,undo("reversal.class","class.001"));
history=await J.append(history,classify("class.002","posted.001","refund"));
history=await J.append(history,review("review.002","posted.001","class.002"));
report=await J.report(history);
assert.equal(report.earnedIncomeUsd,0,"Refund reclassification cannot count as new income");
assert.equal(report.returnedCapitalUsd,125);
assert.equal(report.ownerReviewedByClass.refund,125);
assert.equal(report.ownerReviewedByClass.earned_income,undefined);
await assert.rejects(J.append(history,undo("reversal.same","review.001")),/active non-reversal/);
await assert.rejects(J.append(history,undo("reversal.reverse","reversal.class")),/active non-reversal/);
history=await J.append(history,posted("posted.002","bank.posting.b",2000,"debit"));
await assert.rejects(J.append(history,classify("class.003","posted.002","investment_income")),/direction/);
history=await J.append(history,classify("class.003","posted.002","business_expense"));
report=await J.report(history);
assert.equal(report.closeGate.status,"HOLD");
assert.equal(report.nonReviewedPostings,1);
history=await J.append(history,review("review.003","posted.002","class.003"));
report=await J.report(history);
assert.equal(report.ownerReviewedByClass.business_expense,20);
assert.equal(report.returnedCapitalUsd,125);
assert.equal(report.closeGate.status,"JOURNAL_REVIEW_COMPLETE_ONLY");
let tampered=JSON.parse(JSON.stringify(history));
tampered[0].data.amountCents=1;
await assert.rejects(J.verify(tampered),/modified/);
tampered=JSON.parse(JSON.stringify(history));
tampered[1].prevHash="f".repeat(64);
await assert.rejects(J.verify(tampered),/sequence or hash/);
tampered=JSON.parse(JSON.stringify(history));
tampered.splice(1,1);
await assert.rejects(J.verify(tampered),/sequence or hash/);
await assert.rejects(J.append(history,e("bad.note","POSTED",{sourceId:"123456789012345",postedDate:"2026-11-01",direction:"debit",amountCents:100,currency:"USD",evidenceId:"safe.ref.001"})),/Invalid posted/);
await assert.rejects(J.append(history,e("bad.extra","POSTED",{sourceId:"bank.new",postedDate:"2026-11-01",direction:"debit",amountCents:100,currency:"USD",evidenceId:"safe.ref.001",accountNumber:"999999"})),/Unsupported or missing/);
await assert.rejects(J.append(history,{...posted("bad.time","new.ref",100),"timestamp":"not-a-time"}),/timestamp/);
assert.match(source,/NOT an authenticated signature/);
assert.doesNotMatch(source,/localStorage|sessionStorage|indexedDB|fetch\s*\(|XMLHttpRequest|sendBeacon|WebSocket/);
console.log("IncomeOS event journal QA passed: SHA-256 tamper chains, strict IDs, independent posted sources, reversible classification, refunds separate from earnings, fail-closed owner review.");
